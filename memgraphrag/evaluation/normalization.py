"""Text normalization shared by every MemGraphRAG evaluator.

Provenance: ``normalize_answer`` follows the MRQA / SQuAD official evaluation
recipe as ported in ``MemGraphRAG/code/src/utils/eval_utils.py`` (lowercase,
strip punctuation, drop articles, collapse whitespace). Two steps are added here
because the research script scored short extractive spans while this server
returns chat-model prose: Unicode folding (models emit typographic dashes and
quotes that a raw comparison scores as a miss) and Markdown de-decoration
(``**Paris**`` must normalize to ``paris``, not ``paris`` with stray asterisks).

Every decision frozen in this module is documented in ``docs/Evaluation.md``;
the paper (arXiv:2606.00610) does not define them.
"""

from __future__ import annotations

import re
import string
import unicodedata

#: Typographic characters models emit where the gold answer uses ASCII. Folding
#: them keeps "1941-1945" and "1941–1945" from scoring as different answers.
_UNICODE_FOLD = {
    **dict.fromkeys(map(ord, "‐‑‒–—―−"), "-"),
    **dict.fromkeys(map(ord, "‘’‛′"), "'"),
    **dict.fromkeys(map(ord, "“”‟″"), '"'),
    ord(" "): " ",
    ord("…"): "...",
}

#: Markdown decoration stripped before punctuation removal. Emphasis markers are
#: also punctuation, but they must go *before* tokenisation so that "**Paris**"
#: yields one token rather than gluing the markers onto the word.
_MARKDOWN_INLINE = re.compile(r"(\*\*|__|\*|_|`+|~~)")
_MARKDOWN_BLOCK = re.compile(r"^\s{0,3}(#{1,6}\s+|>\s+|[-*+]\s+|\d+[.)]\s+)", re.MULTILINE)
_MARKDOWN_LINK = re.compile(r"\[([^\]]*)\]\([^)]*\)")

#: Inline citation markers the QA prompt asks the model to emit ("[1]", "【1】").
_CITATION = re.compile(r"[\[【]\s*\d+(?:\s*,\s*\d+)*\s*[\]】]")

_ARTICLES = re.compile(r"\b(a|an|the)\b")
_PUNCTUATION = dict.fromkeys(map(ord, string.punctuation), " ")


def strip_markdown(text: str) -> str:
    """Remove Markdown decoration and citation markers, keeping the words.

    Answers generated by the service are Markdown; gold answers are bare spans.
    Without this step a correct ``**Chris Evans**`` never matches ``Chris Evans``.
    """
    text = _MARKDOWN_LINK.sub(r"\1", text)
    text = _MARKDOWN_BLOCK.sub("", text)
    text = _MARKDOWN_INLINE.sub("", text)
    return _CITATION.sub(" ", text)


def normalize_answer(answer: str) -> str:
    """Normalize an answer string to the frozen EXEIO comparison form.

    Order matters: Unicode folding, then Markdown stripping, then lowercase,
    then punctuation to spaces, then article removal, then whitespace collapse.
    Punctuation becomes a **space** rather than being deleted (the MRQA script
    deletes it) because deletion silently welds tokens together: "U.S.-based"
    would normalize to "usbased" and never match "us based".
    """
    text = (answer or "").translate(_UNICODE_FOLD)
    text = unicodedata.normalize("NFKC", text)
    text = strip_markdown(text)
    text = text.lower()
    text = text.translate(_PUNCTUATION)
    text = _ARTICLES.sub(" ", text)
    return " ".join(text.split())


def normalize_tokens(answer: str) -> list[str]:
    """Normalized whitespace tokens of ``answer`` (the unit of every QA metric)."""
    normalized = normalize_answer(answer)
    return normalized.split() if normalized else []


def normalize_doc_key(title: str) -> str:
    """Identity key for a retrieved / gold document.

    Retrieval metrics compare document *identities*, not prose, so this is a
    tighter form than :func:`normalize_answer`: articles are kept (dropping them
    would merge the distinct Wikipedia titles "The Newcomers" and "Newcomers")
    and punctuation is removed outright so that "Lothair II" and "Lothair II."
    are one key.
    """
    text = (title or "").translate(_UNICODE_FOLD)
    text = unicodedata.normalize("NFKC", text).lower()
    text = text.translate(_PUNCTUATION)
    return " ".join(text.split())
